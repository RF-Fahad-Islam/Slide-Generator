import { TemplateDefinition, CustomThemeColors } from '../types';

export function createCustomTemplateDefinition(customTheme: CustomThemeColors): TemplateDefinition {
  // Determine if theme background is light or dark
  let isLight = false;
  const bgUpper = customTheme.bg.toUpperCase().replace('#', '');
  if (bgUpper.startsWith('F') || bgUpper.startsWith('E') || bgUpper === 'FFFFFF') {
    isLight = true;
  }

  const cleanHex = (h: string) => h ? h.replace('#', '') : '1E293B';

  return {
    id: 'custom-theme',
    name: customTheme.name || 'Custom Built Theme',
    description: 'User customized theme colors',
    previewGradient: "from-amber-500 via-indigo-600 to-slate-900",
    themeType: isLight ? 'light' : 'dark',
    category: 'custom' as any,
    styles: {
      bgClass: isLight ? 'bg-slate-50 text-slate-900' : 'bg-slate-950 text-slate-100',
      cardBg: isLight ? 'bg-white border-2 border-slate-200 shadow-xl' : 'bg-slate-900/90 border border-slate-800 shadow-2xl',
      borderClass: '',
      titleColor: 'font-extrabold',
      badgeBg: 'border',
      badgeText: 'font-extrabold',
      optionBg: 'border',
      optionHover: '',
      optionSelectedBg: 'border-2 shadow-md',
      optionSelectedBorder: '',
      correctBadgeBg: 'border-2',
      accentColor: customTheme.accentColor || customTheme.titleColor || '#f59e0b',
      fontFamily: "'Hind Siliguri', sans-serif",
      hexColors: {
        bg: cleanHex(customTheme.bg),
        cardBg: cleanHex(customTheme.cardBg),
        cardBorder: cleanHex(customTheme.cardBorder),
        titleColor: cleanHex(customTheme.titleColor),
        textColor: cleanHex(customTheme.textColor),
        badgeFill: cleanHex(customTheme.badgeBg),
        badgeText: cleanHex(customTheme.badgeText),
        optionBg: cleanHex(customTheme.optionBg),
        optionBorder: cleanHex(customTheme.optionBorder),
        optionSelectedBg: cleanHex(customTheme.optionSelectedBg),
        optionSelectedBorder: cleanHex(customTheme.optionSelectedBorder),
        optionSelectedText: cleanHex(customTheme.optionSelectedText),
      },
    },
  };
}

